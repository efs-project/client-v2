// Builds apps/web/public/icons/efs-icons.svg: one same-origin SVG sprite holding every icon the
// app renders. Web Awesome's <wa-icon> normally fetches each icon and assigns it with innerHTML,
// which enforced Trusted Types forbids (the icon silently never renders). In sprite-sheet mode it
// renders <svg><use href="…#id"> through Lit instead: no innerHTML, no fetch, no CDN.
//
// Sources (both Font Awesome Free, icons CC BY 4.0, attribution kept in the sprite and in
// THIRD_PARTY_LICENSES.txt):
//   - Web Awesome's own system icon set (the icons its components request internally);
//   - the app icons listed in APP_ICONS, from @fortawesome/fontawesome-free.
// With --write the sprite is regenerated; without it, the build fails if the file has drifted.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname } from 'node:path';
import { WEB } from './paths.ts';

/** Icons the app itself uses, by Font Awesome Free solid name. Add here, then run `pnpm icons`. */
export const APP_ICONS = [
  'arrow-down',
  'arrow-up',
  'bars',
  'circle-check',
  'circle-exclamation',
  'circle-info',
  'download',
  'file',
  'folder',
  'gear',
  'network-wired',
  'plus',
  'rotate-right',
  'server',
  'trash',
  'triangle-exclamation',
  'upload',
] as const;

const OUT = `${WEB}public/icons/efs-icons.svg`;
const IDS_OUT = `${WEB}src/ui/wa/icon-ids.ts`;
const require = createRequire(import.meta.url);
const FA_DIR = `${dirname(require.resolve('@fortawesome/fontawesome-free/package.json'))}/svgs/solid/`;

function symbol(id: string, svg: string): string {
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1];
  if (!viewBox || inner === undefined) throw new Error(`icon ${id}: not an SVG`);
  const body = inner.replace(/<!--[\s\S]*?-->/g, '').trim();
  if (/<(script|foreignObject)\b|\son[a-z]+=|href=/i.test(body)) {
    throw new Error(`icon ${id}: contains active or linked content`);
  }
  return `<symbol id="${id}" viewBox="${viewBox}">${body}</symbol>`;
}

export interface IconBuild {
  readonly sprite: string;
  /** TypeScript listing every symbol id, so resolvers and app code can't reference a missing icon. */
  readonly ids: string;
}

export async function buildIcons(): Promise<IconBuild> {
  const system = (await import(
    // Resolved from this package's own devDependency, pinned to the app's version.
    '@awesome.me/webawesome/dist/components/icon/library.system.js'
  )) as { icons: Record<string, Record<string, string>> };
  const symbols: string[] = [];
  const systemIds: Record<string, string[]> = {};
  for (const variant of Object.keys(system.icons).sort()) {
    systemIds[variant] = Object.keys(system.icons[variant] ?? {}).sort();
    const set = system.icons[variant] ?? {};
    for (const name of Object.keys(set).sort()) {
      symbols.push(symbol(`system-${variant}-${name}`, set[name] as string));
    }
  }
  for (const name of [...APP_ICONS].sort()) {
    symbols.push(symbol(`app-${name}`, readFileSync(`${FA_DIR}${name}.svg`, 'utf8')));
  }
  const sprite = [
    '<svg xmlns="http://www.w3.org/2000/svg">',
    '<!-- Font Awesome Free by @fontawesome - https://fontawesome.com',
    '     License - https://fontawesome.com/license/free (Icons: CC BY 4.0). Generated by tools/build/icons.ts. -->',
    ...symbols,
    '</svg>',
    '',
  ].join('\n');
  const list = (names: readonly string[]) => names.map((n) => `'${n}'`).join(', ');
  const ids = [
    '// Generated by tools/build/icons.ts from the same sources as public/icons/efs-icons.svg.',
    '// Do not edit; run `pnpm icons`.',
    '',
    `export const SYSTEM_ICONS = {`,
    ...Object.entries(systemIds).map(([v, names]) => `  ${v}: [${list(names)}],`),
    `} as const;`,
    '',
    `export const APP_ICONS = [${list([...APP_ICONS].sort())}] as const;`,
    'export type AppIcon = (typeof APP_ICONS)[number];',
    '',
  ].join('\n');
  return { sprite, ids };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { sprite, ids } = await buildIcons();
  const outputs: Array<[string, string]> = [
    [OUT, sprite],
    [IDS_OUT, ids],
  ];
  if (process.argv.includes('--write')) {
    for (const [path, text] of outputs) writeFileSync(path, text);
    console.log('icons: wrote sprite and ids');
  } else {
    for (const [path, text] of outputs) {
      let current = '';
      try {
        current = readFileSync(path, 'utf8');
      } catch {}
      if (current !== text) {
        console.error(`${path} is out of date; run pnpm icons`);
        process.exit(1);
      }
    }
    console.log('icons: sprite and ids are current');
  }
}
